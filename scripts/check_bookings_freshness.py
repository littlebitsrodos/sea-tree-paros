#!/usr/bin/env python3
"""Fail when bookings.json is older than the hourly calendar refresh allows.

The public site reads /bookings.json. That file is regenerated by the
scheduled deploy. If GitHub has disabled the schedule, the timestamp stops
moving while the page still looks open. This check makes that visible.
"""
from __future__ import annotations

import argparse
import json
import sys
import urllib.request
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Any


DEFAULT_MAX_AGE_DAYS = 2
DEFAULT_URL = "https://seatree.gr/bookings.json"


def parse_generated_at(value: str) -> datetime:
    text = value.strip()
    if text.endswith("Z"):
        text = text[:-1] + "+00:00"
    parsed = datetime.fromisoformat(text)
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    return parsed.astimezone(timezone.utc)


def freshness_errors(
    payload: dict[str, Any],
    now: datetime,
    max_age_days: float = DEFAULT_MAX_AGE_DAYS,
) -> list[str]:
    if now.tzinfo is None:
        raise ValueError("now must be timezone-aware")

    raw = payload.get("generated_at")
    if not isinstance(raw, str) or not raw.strip():
        return ["bookings.json is missing generated_at"]

    try:
        generated_at = parse_generated_at(raw)
    except ValueError as exc:
        return [f"bookings.json generated_at is invalid: {exc}"]

    age = now.astimezone(timezone.utc) - generated_at
    if age > timedelta(days=max_age_days):
        age_days = age.total_seconds() / 86400
        return [
            "bookings.json is stale: "
            f"generated_at={generated_at.isoformat(timespec='seconds')} "
            f"age_days={age_days:.1f} max_age_days={max_age_days}"
        ]
    return []


def load_json_file(path: Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def fetch_json(url: str, timeout: int = 20) -> dict[str, Any]:
    req = urllib.request.Request(
        url,
        headers={
            "Accept": "application/json",
            "Cache-Control": "no-cache",
            "User-Agent": "seatree-freshness-check/1.0 (+https://seatree.gr)",
        },
    )
    with urllib.request.urlopen(req, timeout=timeout) as resp:
        return json.loads(resp.read().decode("utf-8"))


def report(payload: dict[str, Any], now: datetime, max_age_days: float) -> int:
    generated_at = payload.get("generated_at")
    print(f"generated_at={generated_at}")
    print(f"checked_at={now.isoformat(timespec='seconds')}")
    print(f"max_age_days={max_age_days}")
    errors = freshness_errors(payload, now, max_age_days)
    if errors:
        for error in errors:
            print(error, file=sys.stderr)
        return 1
    print("bookings.json is fresh")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--file")
    source.add_argument("--url", default=None)
    parser.add_argument("--max-age-days", type=float, default=DEFAULT_MAX_AGE_DAYS)
    args = parser.parse_args(argv)

    if args.file:
        payload = load_json_file(Path(args.file))
    else:
        payload = fetch_json(args.url or DEFAULT_URL)

    return report(payload, datetime.now(timezone.utc), args.max_age_days)


if __name__ == "__main__":
    sys.exit(main())
